const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('cacamba', {
  getSources: () => ipcRenderer.invoke('screen:sources'),
  selectSource: (sel) => ipcRenderer.invoke('screen:select', sel),
  version: () => ipcRenderer.invoke('app:version'),
  openExternal: (url) => ipcRenderer.invoke('app:open', url),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  updateState: () => ipcRenderer.invoke('update:state'),
  setFullscreen: (on) => ipcRenderer.invoke('win:fullscreen', on),
  isFullscreen: () => ipcRenderer.invoke('win:isFullscreen'),
  minimize: () => ipcRenderer.invoke('win:minimize'),
  close: () => ipcRenderer.invoke('win:close'),
  onFullscreen: (cb) => ipcRenderer.on('fullscreen', (_e, on) => cb(on)),
  onShortcut: (cb) => ipcRenderer.on('shortcut', (_e, name) => cb(name)),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, info) => cb(info)),
  bot: {
    open: () => ipcRenderer.invoke('bot:open'),
    play: (id) => ipcRenderer.invoke('bot:play', id),
    ctl: (c) => ipcRenderer.invoke('bot:ctl', c),
    close: () => ipcRenderer.invoke('bot:close'),
    search: (q, n) => ipcRenderer.invoke('bot:search', q, n),
    related: (id) => ipcRenderer.invoke('bot:related', id),
    onState: (cb) => ipcRenderer.on('bot-state', (_e, s) => cb(s)),
  },
  vozes: {
    estado: () => ipcRenderer.invoke('vozes:estado'),
    catalogo: (forcar) => ipcRenderer.invoke('vozes:catalogo', forcar),
    instalarMotor: () => ipcRenderer.invoke('vozes:instalarMotor'),
    baixar: (id) => ipcRenderer.invoke('vozes:baixar', id),
    apagar: (id) => ipcRenderer.invoke('vozes:apagar', id),
    iniciar: (id, opts) => ipcRenderer.invoke('vozes:iniciar', id, opts),
    processar: (buf) => ipcRenderer.invoke('vozes:processar', buf),
    info: () => ipcRenderer.invoke('vozes:info'),
    parar: () => ipcRenderer.invoke('vozes:parar'),
    onProgresso: (cb) => ipcRenderer.on('vozes-prog', (_e, d) => cb(d)),
  },
  atividade: {
    ligar: (on) => ipcRenderer.invoke('atividade:ligar', on),
    get: () => ipcRenderer.invoke('atividade:get'),
    onMudou: (cb) => ipcRenderer.on('atividade', (_e, a) => cb(a)),
  },
  platform: process.platform,
});
